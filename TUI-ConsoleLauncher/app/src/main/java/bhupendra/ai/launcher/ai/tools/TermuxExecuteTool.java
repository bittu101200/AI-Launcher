public class TermuxExecuteTool extends BaseAITool {

    private static final String TAG = "TermuxExecuteTool";
    private MainPack mainPack;

    public TermuxExecuteTool(String name, String description, Map<String, String> parameters, ToolRiskClass riskClass) {
        super(name, description, parameters, riskClass);
    }

    public void setMainPack(MainPack mainPack) {
        this.mainPack = mainPack;
    }

    @Override
    public String execute(Context context, JSONObject args) throws Exception {
            
            String cmd = args.getString("command");
            String argStr = args.optString("arguments", "");
            
            if (!TermuxManager.isTermuxInstalled(context)) {
                return "[error: Termux is not installed]";
            }

            String[] finalArgs = argStr.isEmpty() ? new String[0] : argStr.split(" ");
            // Run synchronously for tool execution so AI can see the output
            return TermuxManager.runCommandSync(context, cmd, finalArgs, null, 15000); // 15s timeout
    }
}
